export function getDateLocale(lang: string) {
  switch(lang) {
    case 'es': return es;
    case 'fr': return fr;
    case 'de': return de;
    case 'zh': return zhCN;
    case 'ja': return ja;
    case 'ko': return ko;
    case 'ru': return ru;
    case 'ar': return ar;
    default: return enUS;
  }
}

export type LanguageCode = keyof typeof translations;

export function useTranslation(lang: string = 'en') {
  return function t(key: keyof typeof translations['en']) {
    return (translations as any)[lang]?.[key] || translations['en'][key];
  };
}
